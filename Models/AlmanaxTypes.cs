    /// <summary>Type complet (« Équipement · Anneau »), chaîne vide si l'offrande est inconnue.</summary>
    public static string For(string resource)
        => resource != null && ByName.TryGetValue(resource, out var t) ? t : "";

    /// <summary>Catégorie seule : « Ressource », « Équipement » ou « Consommable ».</summary>
    public static string CategoryOf(string typeText)
    {
        if (string.IsNullOrEmpty(typeText)) return "";
        int i = typeText.IndexOf(" · ", StringComparison.Ordinal);
        return i < 0 ? typeText : typeText.Substring(0, i);
    }
